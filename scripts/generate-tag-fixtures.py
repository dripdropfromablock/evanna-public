"""Stream-copy original Evanna test audio; never read or modify the user's music."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import struct

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--ffmpeg", default="ffmpeg")
args = parser.parse_args()
assets = Path(__file__).resolve().parent.parent / "app/src/androidTest/assets"
output = assets / "tags"
output.mkdir(exist_ok=True)
metadata = {
    "album_artist": "Evanna ensemble é", "track": "2/17", "disc": "1/2", "date": "2019-08-03",
    "genre": "Test genre", "composer": "Composer ü", "compilation": "1",
}
for name, source, options in [
    ("album.flac", "decoder/stereo-16.flac", []),
    ("album.m4a", "decoder/stereo-16.m4a", []),
    ("album.ogg", "decoder-extended/tone.ogg", []),
    ("id3v23.mp3", "decoder-extended/tone.mp3", ["-id3v2_version", "3"]),
    ("id3v24.mp3", "decoder-extended/tone.mp3", ["-id3v2_version", "4"]),
    ("totals.flac", "decoder/stereo-16.flac", []),
    ("bounded.flac", "decoder/stereo-16.flac", []),
]:
    tags = dict(metadata)
    if name == "totals.flac":
        tags.update(track="3", tracktotal="18", disc="2", disctotal="3")
    if name == "bounded.flac":
        tags["composer"] = "x" * 5000
    command = [args.ffmpeg, "-v", "error", "-y", "-i", str(assets / source), "-map_metadata", "-1", "-c", "copy"]
    for key, value in tags.items():
        command.extend(["-metadata", f"{key}={value}"])
    subprocess.run(command + options + [str(output / name)], check=True)

# Add an original track-level composer that conflicts with the container composer.
def atom(kind, payload):
    return struct.pack(">I", len(payload) + 8) + kind + payload

def atoms(data):
    offset = 0
    while offset < len(data):
        size, kind = struct.unpack_from(">I4s", data, offset)
        assert size >= 8 and offset + size <= len(data)
        yield kind, data[offset + 8:offset + size]
        offset += size

original = list(atoms((output / "album.m4a").read_bytes()))
assert original[-1][0] == b"moov", "The fixture must keep moov after media data so chunk offsets stay unchanged"
children = list(atoms(original[-1][1]))
tag = atom(b"\xa9wrt", atom(b"data", bytes.fromhex("0000000100000000") + b"Stream composer"))
handler = atom(b"hdlr", bytes(8) + b"mdir" + bytes(13))
udta = atom(b"udta", atom(b"meta", bytes(4) + handler + atom(b"ilst", tag)))
original[-1] = (b"moov", b"".join(atom(kind, payload + udta if kind == b"trak" else payload) for kind, payload in children))
(output / "precedence.m4a").write_bytes(b"".join(atom(kind, payload) for kind, payload in original))

files = sorted(p for p in output.iterdir() if p.suffix in (".flac", ".m4a", ".mp3", ".ogg"))
(output / "SHA256SUMS.txt").write_text("".join(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}\n" for p in files), encoding="utf-8")
version = subprocess.check_output([args.ffmpeg, "-version"], text=True).splitlines()[0]
(output / "README.md").write_text(
    "# Original album tag fixtures\n\nGenerated by `scripts/generate-tag-fixtures.py` using " + version + ".\n\n"
    "Audio packets are copied from the existing decoder fixtures; metadata is original test data. "
    "`TagsProbe` checks tags without playback and compares decoded PCM to each source. "
    "FLAC/Vorbis carry a full date; MP4/ID3 may normalize dates/totals. "
    "Separate totals use FLAC comments; bounded.flac has a 5,000-byte composer. "
    "precedence.m4a adds a crafted track-level composer overriding the container composer without moving audio. "
    "The existing tagless stereo-16.wav is the empty-tags control.\n", encoding="utf-8")
print(f"Generated {len(files)} tag fixtures with SHA-256 sums.")
