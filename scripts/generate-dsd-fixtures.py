"""Original DSD64 test files: the same 1 kHz bitstream as DSF (LSB first, block planar) and DSDIFF (MSB first, interleaved)."""
import hashlib
import math
from pathlib import Path
import struct

RATE = 2822400
SAMPLES = 9 * 4096 * 8  # whole DSF blocks, so no padding bits are decoded
output = Path(__file__).resolve().parent.parent / "app/src/androidTest/assets/decoder-dsd"
output.mkdir(parents=True, exist_ok=True)


def modulate(phase):
    """Second-order sigma-delta of a 0.5-amplitude 1 kHz sine; deterministic, no dependencies."""
    bits, first, second, y = [], 0.0, 0.0, 0.0
    for n in range(SAMPLES):
        x = 0.5 * math.sin(2 * math.pi * 1000 * n / RATE + phase)
        first += x - y
        second += first - y
        y = 1.0 if second >= 0 else -1.0
        bits.append(1 if y > 0 else 0)
    return bits


def pack(bits, lsb_first):
    return bytes(sum(bits[i + k] << (k if lsb_first else 7 - k) for k in range(8)) for i in range(0, len(bits), 8))


left, right = modulate(0.0), modulate(math.pi / 2)
# DSF: per-channel 4096-byte blocks, little-endian headers.
lsb = [pack(left, True), pack(right, True)]
data = b"".join(lsb[c][i:i + 4096] for i in range(0, len(lsb[0]), 4096) for c in range(2))
fmt = struct.pack("<IIIIIIQII", 1, 0, 2, 2, RATE, 1, SAMPLES, 4096, 0)
total = 28 + 12 + len(fmt) + 12 + len(data)
dsf = b"DSD " + struct.pack("<QQQ", 28, total, 0) + b"fmt " + struct.pack("<Q", 12 + len(fmt)) + fmt + b"data" + struct.pack("<Q", 12 + len(data)) + data
(output / "tone.dsf").write_bytes(dsf)
# DSDIFF: big-endian IFF chunks, byte-interleaved channels.
msb = [pack(left, False), pack(right, False)]
sound = bytes(b for pair in zip(*msb) for b in pair)
def chunk(kind, body):
    return kind + struct.pack(">Q", len(body)) + body + (b"\0" if len(body) % 2 else b"")
name = b"not compressed"
prop = b"SND " + chunk(b"FS  ", struct.pack(">I", RATE)) + chunk(b"CHNL", struct.pack(">H", 2) + b"SLFTSRGT") + \
    chunk(b"CMPR", b"DSD " + bytes([len(name)]) + name)
body = b"DSD " + chunk(b"FVER", struct.pack(">I", 0x01050000)) + chunk(b"PROP", prop) + chunk(b"DSD ", sound)
(output / "tone.dff").write_bytes(b"FRM8" + struct.pack(">Q", len(body)) + body)
files = sorted(output.glob("tone.*"))
(output / "SHA256SUMS.txt").write_text("".join(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}\n" for p in files), encoding="utf-8")
(output / "README.md").write_text("# Original DSD64 fixtures\n\nGenerated by `scripts/generate-dsd-fixtures.py`: the same 1 kHz, 0.5-amplitude second-order "
    "sigma-delta bitstream (left sine, right cosine) as DSF and DSDIFF, " + str(SAMPLES) + " DSD samples per channel. No third-party audio.\n", encoding="utf-8")
print("Generated", [p.name for p in files])
