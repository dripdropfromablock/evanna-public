param([Parameter(Mandatory)][string]$Ffmpeg, [Parameter(Mandatory)][string]$MonkeysAudio)
$ErrorActionPreference = 'Stop'
# WavPack and TTA come from FFmpeg's encoders. FFmpeg has no APE encoder, so APE comes from the
# Monkey's Audio 13.45 console tool (BSD-3-Clause, built from the official SDK; host-only).
# Inputs are committed lossless fixtures, so every output must decode to exactly the same samples.
$assets = Join-Path $PSScriptRoot '../../app/src/androidTest/assets'
$temporary = Join-Path $PSScriptRoot '../../.tools/decoder-fixtures'
$tagged = Join-Path $assets 'tags-apev2'
New-Item -ItemType Directory -Force $temporary, $tagged | Out-Null
function Encode([string]$source, [string]$target, [string[]]$options) {
    & $Ffmpeg -hide_banner -loglevel error -y -i $source -map_metadata -1 @options $target
    if ($LASTEXITCODE -ne 0) { throw "Encoding failed: $target" }
}
function Ape([string]$wav, [string]$target) {
    Remove-Item -LiteralPath $target -ErrorAction SilentlyContinue
    & $MonkeysAudio $wav $target -c2000 | Out-Null
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $target)) { throw "APE encoding failed: $target" }
}
foreach ($bits in 16, 24) {
    $wav = Join-Path $assets "decoder/stereo-$bits.wav"
    $format = if ($bits -eq 16) { 's16' } else { 's32' }
    Encode $wav (Join-Path $assets "decoder/stereo-$bits.wv") @('-c:a', 'wavpack', '-sample_fmt', "${format}p", '-bits_per_raw_sample', "$bits", '-frame_size', '4096')
    Encode $wav (Join-Path $assets "decoder/stereo-$bits.tta") @('-c:a', 'tta', '-sample_fmt', $format, '-bits_per_raw_sample', "$bits")
    Ape $wav (Join-Path $assets "decoder/stereo-$bits.ape")
}
$seek = Join-Path $assets 'decoder-seek/seek.flac'  # 24-bit
Encode $seek (Join-Path $assets 'decoder-seek/seek.wv') @('-c:a', 'wavpack', '-sample_fmt', 's32p', '-bits_per_raw_sample', '24')
Encode $seek (Join-Path $assets 'decoder-seek/seek.tta') @('-c:a', 'tta', '-sample_fmt', 's32', '-bits_per_raw_sample', '24')
Encode $seek (Join-Path $temporary 'seek.wav') @('-c:a', 'pcm_s24le')
Ape (Join-Path $temporary 'seek.wav') (Join-Path $assets 'decoder-seek/seek.ape')
& $Ffmpeg -hide_banner -loglevel error -y -f lavfi -i 'sine=frequency=997:sample_rate=384000:duration=1' -ac 2 -map_metadata -1 -c:a tta -sample_fmt s32 -bits_per_raw_sample 24 (Join-Path $assets 'decoder-extended/hires-384k.tta')
if ($LASTEXITCODE -ne 0) { throw 'High-rate TTA fixture encoding failed' }
# Same original metadata as tags/album.*, written as APEv2 (the tag format WavPack, TTA and APE share).
$metadata = @("album_artist=Evanna ensemble $([char]0xE9)", 'track=2/17', 'disc=1/2', 'date=2019-08-03',
    'genre=Test genre', "composer=Composer $([char]0xFC)", 'compilation=1')
$options = @('-c', 'copy') + @($metadata | ForEach-Object { '-metadata'; $_ })
foreach ($extension in 'wv', 'tta') {
    Encode (Join-Path $assets "decoder/stereo-16.$extension") (Join-Path $tagged "album.$extension") $options
}
$files = Get-ChildItem $tagged -File | Where-Object Extension -in '.wv', '.tta' | Sort-Object Name
$sums = $files | ForEach-Object { "$((Get-FileHash $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant())  $($_.Name)" }
Set-Content -LiteralPath (Join-Path $tagged 'SHA256SUMS.txt') -Value $sums -Encoding ascii
$version = (& $Ffmpeg -version | Select-Object -First 1)
Set-Content -LiteralPath (Join-Path $tagged 'README.md') -Encoding ascii -Value @(
    '# APEv2 tag fixtures', '',
    "Generated by ``scripts/tests/create-lossless-fixtures.ps1`` using $version.", '',
    'Audio packets are copied from the WavPack/TTA decoder fixtures; metadata matches `tags/album.*`. FFmpeg cannot write APE files, so APE tags are covered through the same APEv2 reader.')
Get-ChildItem (Join-Path $assets 'decoder'), (Join-Path $assets 'decoder-seek'), $tagged -File |
    Where-Object Extension -in '.wv', '.tta', '.ape' | Get-FileHash -Algorithm SHA256 | Select-Object Hash, @{Name='File';Expression={Split-Path $_.Path -Leaf}}
