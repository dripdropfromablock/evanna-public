"""Original gain tags on Evanna test audio; verify emitted metadata and unchanged S32 PCM."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--ffmpeg", required=True)
parser.add_argument("--ffprobe", required=True)
args = parser.parse_args()
assets = Path(__file__).resolve().parent.parent / "app/src/androidTest/assets"
output = assets / "loudness-tags"
output.mkdir(exist_ok=True)
gain = dict(replaygain_track_gain="-4.25 dB", replaygain_album_gain="-2.50 dB", replaygain_track_peak="0.5", replaygain_album_peak="0.9", iTunNORM="00000000")
cases = [
    ("gain.flac", "decoder/stereo-16.flac", gain),
    ("gain.mp3", "decoder-extended/tone.mp3", gain),
    ("gain.ogg", "decoder-extended/tone.ogg", gain),
    ("gain.m4a", "decoder/stereo-16.m4a", {}),
    ("r128.opus", "decoder-extended/tone.opus", dict(R128_TRACK_GAIN="-2560", R128_ALBUM_GAIN="256")),
    ("bounded.flac", "decoder/stereo-16.flac", dict(REPLAYGAIN_TRACK_GAIN="NaN", REPLAYGAIN_ALBUM_GAIN="x" * 129)),
]
sources = {}
for name, source, tags in cases:
    command = [args.ffmpeg, "-v", "error", "-y", "-i", str(assets / source), "-map_metadata", "-1", "-c", "copy"]
    for key, value in tags.items():
        command.extend(["-metadata", f"{key}={value}"])
    subprocess.run(command + [str(output / name)], check=True)
    sources[name] = source


def atom(kind, payload):
    return struct.pack(">I4s", len(payload) + 8, kind) + payload


def atoms(data):
    offset = 0
    while offset < len(data):
        size, kind = struct.unpack_from(">I4s", data, offset)
        assert size >= 8 and offset + size <= len(data)
        yield kind, data[offset + 8:offset + size]
        offset += size


def freeform(tags):
    entries = b""
    for key, value in tags.items():
        entries += atom(b"----", atom(b"mean", bytes(4) + b"com.apple.iTunes") + atom(b"name", bytes(4) + key.encode()) + atom(b"data", bytes.fromhex("0000000100000000") + value.encode()))
    handler = atom(b"hdlr", bytes(8) + b"mdir" + bytes(13))
    return atom(b"udta", atom(b"meta", bytes(4) + handler + atom(b"ilst", entries)))


original = list(atoms((output / "gain.m4a").read_bytes()))
assert original[-1][0] == b"moov", "Metadata must follow media data so chunk offsets stay unchanged"
original[-1] = (b"moov", original[-1][1] + freeform(gain))
(output / "gain.m4a").write_bytes(b"".join(atom(kind, payload) for kind, payload in original))
children = list(atoms(original[-1][1]))
# The pinned demuxer reads mdta key definitions globally; the indexed value belongs to the track.
handler = atom(b"hdlr", bytes(8) + b"mdta" + bytes(13))
keys = atom(b"keys", bytes(4) + struct.pack(">I", 1) + atom(b"mdta", b"replaygain_track_gain"))
entry = atom(struct.pack(">I", 1), atom(b"data", bytes.fromhex("0000000100000000") + b"-7.25 dB"))
key_setup = atom(b"udta", atom(b"meta", bytes(4) + handler + keys))
stream_tag = atom(b"udta", atom(b"meta", bytes(4) + atom(b"hdlr", bytes(8) + b"mdir" + bytes(13)) + atom(b"ilst", entry)))
original[-1] = (b"moov", key_setup + b"".join(atom(kind, payload + stream_tag if kind == b"trak" else payload) for kind, payload in children))
(output / "precedence.m4a").write_bytes(b"".join(atom(kind, payload) for kind, payload in original))
sources["precedence.m4a"] = "decoder/stereo-16.m4a"


def pcm_hash(path):
    return hashlib.sha256(subprocess.check_output([args.ffmpeg, "-v", "error", "-i", str(path), "-map", "0:a:0", "-f", "s32le", "-acodec", "pcm_s32le", "-"])).hexdigest()


for name, source in sources.items():
    assert pcm_hash(output / name) == pcm_hash(assets / source), f"PCM changed: {name}"
    metadata = json.loads(subprocess.check_output([args.ffprobe, "-v", "error", "-show_entries", "format_tags:stream_tags", "-of", "json", str(output / name)], text=True))
    found = {key.lower(): value for key, value in metadata.get("format", {}).get("tags", {}).items()}
    for stream in metadata.get("streams", []):
        found.update({key.lower(): value for key, value in stream.get("tags", {}).items()})
    expected = gain.copy() if name in ("gain.m4a", "precedence.m4a") else dict(next(case[2] for case in cases if case[0] == name))
    if name == "precedence.m4a":
        expected["replaygain_track_gain"] = "-7.25 dB"
    assert all(found.get(key.lower()) == value for key, value in expected.items()), f"Gain metadata missing or altered: {name}"
(output / "SHA256SUMS.txt").write_text("".join(f"{hashlib.sha256((output / name).read_bytes()).hexdigest()}  {name}\n" for name in sorted(sources)), encoding="utf-8")
version = subprocess.check_output([args.ffmpeg, "-version"], text=True).splitlines()[0]
(output / "README.md").write_text(
    "# Original loudness tag fixtures\n\nGenerated by scripts/generate-loudness-fixtures.py using " + version + ".\n\n"
    "Existing Evanna test packets are copied unchanged; the generator verifies actual emitted tags and identical decoded S32 hashes. "
    "Fixtures cover FLAC/Vorbis comments, ID3 TXXX, crafted MP4 iTunes freeform atoms, stream-over-container precedence, Opus R128, and invalid/overlong gains. "
    "LoudnessProbe checks Android tag reads and PCM equivalence without audio output. Sound Check is only detected. Host tools are not shipped.\n", encoding="utf-8")
print(f"Generated and verified {len(sources)} loudness tag fixtures using {version}")
