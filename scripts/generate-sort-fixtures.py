"""Add original sort metadata to Evanna's own audio fixtures; never read user music."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--ffmpeg", required=True)
parser.add_argument("--ffprobe", required=True)
args = parser.parse_args()
assets = Path(__file__).resolve().parent.parent / "app/src/androidTest/assets"
output = assets / "sort-tags"
output.mkdir(exist_ok=True)
expected = ["Visible, The", "Artist, The", "Album, The", "Ensemble, The"]
cases = [
    ("sort.flac", "decoder/stereo-16.flac", ["TITLESORT", "ARTISTSORT", "ALBUMSORT", "ALBUMARTISTSORT"], []),
    ("sort.m4a", "decoder/stereo-16.m4a", ["sort_name", "sort_artist", "sort_album", "sort_album_artist"], []),
    ("sort.mp3", "decoder-extended/tone.mp3", ["title-sort", "artist-sort", "album-sort", "albumartistsort"], ["-id3v2_version", "4"]),
    ("bounded.flac", "decoder/stereo-16.flac", ["TITLESORT", "ARTISTSORT", "ALBUMSORT", "ALBUMARTISTSORT"], []),
]
sources = {}
for name, source, keys, options in cases:
    tags = dict(zip(keys, expected))
    tags.update(title="The Visible", artist="The Artist", album="The Album")
    if name == "bounded.flac":
        tags[keys[0]] = "x" * 5000
    command = [args.ffmpeg, "-v", "error", "-y", "-i", str(assets / source), "-map_metadata", "-1", "-c", "copy"]
    for key, value in tags.items():
        command.extend(["-metadata", f"{key}={value}"])
    subprocess.run(command + options + [str(output / name)], check=True)
    sources[name] = source


def atom(kind, payload):
    return struct.pack(">I4s", len(payload) + 8, kind) + payload


def atoms(data):
    offset = 0
    while offset < len(data):
        size, kind = struct.unpack_from(">I4s", data, offset)
        assert size >= 8 and offset + size <= len(data)
        yield kind, data[offset + 8:offset + size]
        offset += size


def metadata_atom(tags):
    data = b"".join(atom(kind, atom(b"data", bytes.fromhex("0000000100000000") + text.encode("utf-8"))) for kind, text in tags)
    handler = atom(b"hdlr", bytes(8) + b"mdir" + bytes(13))
    return atom(b"udta", atom(b"meta", bytes(4) + handler + atom(b"ilst", data)))


# FFmpeg's muxer does not write these Apple sort atoms; retain its packet/container output and add only metadata.
original = list(atoms((output / "sort.m4a").read_bytes()))
assert original[-1][0] == b"moov"
original[-1] = (b"moov", original[-1][1] + metadata_atom(zip([b"sonm", b"soar", b"soal", b"soaa"], expected)))
(output / "sort.m4a").write_bytes(b"".join(atom(kind, payload) for kind, payload in original))


# The track alias must win over a container value; moov stays after media so chunk offsets do not move.
original = list(atoms((output / "sort.m4a").read_bytes()))
assert original[-1][0] == b"moov"
children = list(atoms(original[-1][1]))
udta = metadata_atom([(b"soar", "Stream sort artist")])
original[-1] = (b"moov", b"".join(atom(kind, payload + udta if kind == b"trak" else payload) for kind, payload in children))
(output / "precedence.m4a").write_bytes(b"".join(atom(kind, payload) for kind, payload in original))
sources["precedence.m4a"] = "decoder/stereo-16.m4a"


def pcm_hash(path):
    return subprocess.check_output([args.ffmpeg, "-v", "error", "-i", str(path), "-map", "0:a:0", "-c:a", "pcm_s32le", "-f", "hash", "-hash", "sha256", "-"], text=True).strip()


for name, source in sources.items():
    assert pcm_hash(output / name) == pcm_hash(assets / source), f"Audio changed: {name}"
    result = json.loads(subprocess.check_output([args.ffprobe, "-v", "error", "-show_entries", "format_tags:stream_tags", "-of", "json", str(output / name)], text=True))
    tags = {key.lower(): value for key, value in result.get("format", {}).get("tags", {}).items()}
    for stream in result.get("streams", []):
        tags.update({key.lower(): value for key, value in stream.get("tags", {}).items()})
    keys = next((case[2] for case in cases if case[0] == name), cases[1][2])
    values = expected.copy()
    if name == "bounded.flac":
        values[0] = "x" * 5000
    if name == "precedence.m4a":
        values[1] = "Stream sort artist"
    assert [tags.get(key.lower()) for key in keys] == values, f"Sort metadata absent or changed: {name}"
    assert tags.get("title") == "The Visible" and tags.get("artist") == "The Artist", f"Display metadata changed: {name}"
(output / "SHA256SUMS.txt").write_text("".join(f"{hashlib.sha256((output / name).read_bytes()).hexdigest()}  {name}\n" for name in sorted(sources)), encoding="utf-8")
version = subprocess.check_output([args.ffmpeg, "-version"], text=True).splitlines()[0]
(output / "README.md").write_text(
    "# Original sort-tag fixtures\n\nGenerated by scripts/generate-sort-fixtures.py using " + version + ".\n\n"
    "Audio comes from Evanna's existing original fixtures; only metadata is changed. The generator verifies identical host S32 PCM hashes. "
    "FLAC exercises Vorbis aliases, MP4 Apple sort atoms, MP3 ID3 canonical names, bounded.flac a 5,000-byte sort name, and precedence.m4a a stream alias over container metadata. "
    "TagsProbe checks Android decoding and visible/private metadata separately without playback. Host FFmpeg is a fixture tool and is not shipped with the application.\n", encoding="utf-8")
print(f"Generated and verified {len(sources)} sort fixtures using {version}")
